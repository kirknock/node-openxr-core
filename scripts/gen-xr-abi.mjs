/**
 * Generates src/xr/generated/xr-abi.gen.ts from the vendored OpenXR headers.
 *
 * Compiles third_party/openxr/dump.c (needs gcc), runs it, and converts the
 * emitted SIZE/OFF/I/L facts into:
 *   - named constants (XR_TYPE_*, XR_RESULT_*, states, spaces, flag bits...)
 *   - abiSizes / abiOffsets tables used by xr-abi.ts to self-check the koffi
 *     struct definitions at runtime.
 *
 * Usage: npm run gen:abi   (dev-time codegen only; output is committed)
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dumpSrc = join(root, "third_party/openxr/dump.c");
const includeDir = join(root, "third_party/openxr");
const outFile = join(root, "src/xr/generated/xr-abi.gen.ts");
const binPath = "/tmp/node-openxr-abi-dump";

execFileSync("gcc", ["-I", includeDir, dumpSrc, "-o", binPath], { stdio: "inherit" });
const text = execFileSync(binPath, { encoding: "utf8", maxBuffer: 1 << 20 });

/** @type {Record<string, number>} */
const sizes = {};
/** @type {Record<string, Record<string, number>>} */
const offsets = {};
/** @type {Array<[string, string]>} */
const intConsts = [];

for (const line of text.split("\n")) {
  let m = line.match(/^SIZE\s+(\S+)\s+(\d+)$/);
  if (m) {
    sizes[m[1]] = Number(m[2]);
    continue;
  }
  m = line.match(/^OFF\s+(\S+)\s+(\S+)\s+(\d+)$/);
  if (m) {
    (offsets[m[1]] ??= {})[m[2]] = Number(m[3]);
    continue;
  }
  m = line.match(/^I\s+(\S+)\s+(-?\d+)$/);
  if (m) {
    intConsts.push([m[1], m[2]]);
    continue;
  }
  m = line.match(/^L\s+(\S+)\s+(-?\d+)$/);
  if (m) {
    intConsts.push([m[1], m[2]]);
    continue;
  }
  if (line.trim() !== "") {
    throw new Error(`Unrecognized dump line: ${line}`);
  }
}

const header = `// AUTO-GENERATED by packages/core/scripts/gen-xr-abi.mjs — DO NOT EDIT.
// Derived mechanically (gcc + offsetof/sizeof) from the vendored OpenXR
// headers in packages/core/third_party/openxr (Debian libopenxr-dev 1.0.20, matching the
// installed libopenxr_loader.so.1).

`;

let out = header;
for (const [name, value] of intConsts) {
  out += `export const ${name} = ${value};\n`;
}
out += `\n/** C sizeof(X) for every struct used by the FFI layer (x86-64). */\n`;
out += `export const abiSizes: Record<string, number> = {\n`;
for (const name of Object.keys(sizes).sort()) {
  out += `  ${name}: ${sizes[name]},\n`;
}
out += `};\n\n/** C offsetof(X, field) for every struct field used by the FFI layer. */\n`;
out += `export const abiOffsets: Record<string, Record<string, number>> = {\n`;
for (const name of Object.keys(offsets).sort()) {
  out += `  ${name}: { ${Object.entries(offsets[name])
    .map(([f, o]) => `${f}: ${o}`)
    .join(", ")} },\n`;
}
out += `};\n`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out);
console.log(`wrote ${outFile} (${intConsts.length} constants, ${Object.keys(sizes).length} struct sizes, ${Object.keys(offsets).length} struct offset tables)`);
